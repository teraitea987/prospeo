import { expect, test } from "@playwright/test";
test("recherche, filtres, pagination et absence de résultats", async ({ page }, testInfo) => {
  await page.goto("/recherche");
  await expect(page.getByText(/Toutes les entreprises présentées sont fictives/)).toBeVisible();
  await page.getByRole("button", { name: "Rechercher", exact: true }).click();
  await expect(page.getByRole("status")).toHaveText("12 entreprises fictives trouvées");
  await expect(page.locator(".result-card")).toHaveCount(6);
  await page.getByRole("button", { name: "Suivant" }).click();
  await expect(page.getByText("Page 2 sur 2")).toBeVisible();
  await expect(page.getByRole("button", { name: "Suivant" })).toBeDisabled();
  await page.getByLabel("Ville", { exact: true }).fill("Lyon");
  await page.getByLabel("Secteur d’activité").selectOption("Artisanat");
  await page.getByRole("button", { name: "Rechercher", exact: true }).click();
  await expect(page.getByRole("status")).toHaveText("1 entreprise fictive trouvée");
  await expect(page.getByRole("heading", { name: "Atelier Démo Aurore" })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath("recherche.png"), fullPage: true });
  await page.getByLabel("Ville", { exact: true }).fill("Atlantide");
  await page.getByRole("button", { name: "Rechercher", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Aucune entreprise fictive trouvée" })).toBeVisible();
  await page.getByRole("button", { name: "Réinitialiser" }).click();
  await expect(page.getByLabel("Ville", { exact: true })).toHaveValue("");
  await expect(page.getByRole("status")).toContainText("Choisissez vos critères");
});
test("chargement, erreur réseau et nouvelle tentative", async ({ page }) => {
  await page.goto("/recherche");
  let release!: () => void;
  const gate = new Promise<void>(resolve => { release = resolve; });
  await page.route("**/api/recherche?**", async route => { await gate; await route.fulfill({ status: 503, body: "indisponible" }); });
  await page.getByRole("button", { name: "Rechercher", exact: true }).click();
  await expect(page.getByRole("status")).toHaveText("Recherche en cours…");
  release();
  await expect(page.getByRole("alert").filter({ hasText: "Recherche indisponible" })).toContainText("Recherche indisponible");
  await page.unroute("**/api/recherche?**");
  await page.getByRole("button", { name: "Réessayer" }).click();
  await expect(page.getByRole("status")).toHaveText("12 entreprises fictives trouvées");
});
test("navigation clavier et validation API directe", async ({ page, request }) => {
  await page.goto("/recherche");
  await page.keyboard.press("Tab"); await page.keyboard.press("Enter");
  await expect(page.locator("main")).toBeFocused();
  await page.keyboard.press("Tab");
  await expect(page.getByLabel("Mots-clés")).toBeFocused();
  await page.keyboard.type("atelier");
  await page.keyboard.press("Enter");
  await expect(page.getByRole("status")).toHaveText("2 entreprises fictives trouvées");
  expect((await request.get("/api/recherche?workspaceId=intrus")).status()).toBe(400);
  expect((await request.get("/api/recherche?page=0")).status()).toBe(400);
});
